/**
 * Generates CSS-mask versions of the lucide icons used on product pages.
 *
 *   node scripts/gen-mask-icons.cjs
 *
 * Why: every lucide icon renders a full inline <svg> (~0.8 KB) that Next.js
 * ships twice (HTML + React Server Components payload). Product pages repeat
 * icons dozens of times, which made up a large share of their page weight.
 * The generated components render <span class="ico ico-<name>"> instead; the
 * icon shape comes from a CSS mask built from lucide's own SVG markup, and the
 * colour from currentColor, so they look the same.
 *
 * Outputs (both generated, do not edit by hand):
 *   components/ui/mask-icons.tsx            drop-in replacements for lucide-react
 *   app/(landing)/products/product-icons.css  one mask class per icon
 *
 * To add an icon: import it from "@/components/ui/mask-icons" in a product
 * file and re-run this script (it scans the product files for icon names).
 */
const fs = require("fs");
const path = require("path");
const React = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const lucide = require("lucide-react");

const ROOT = path.join(__dirname, "..");
const PRODUCTS = path.join(ROOT, "app", "(landing)", "products");

function productFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) return productFiles(p);
    return /\.tsx$/.test(e.name) ? [p] : [];
  });
}

const names = new Set();
const importRe = /import\s*\{([^}]*)\}\s*from\s*"(?:lucide-react|@\/components\/ui\/mask-icons)"/g;
for (const file of productFiles(PRODUCTS)) {
  const src = fs.readFileSync(file, "utf8");
  for (const m of src.matchAll(importRe)) {
    for (const raw of m[1].split(",")) {
      const name = raw.trim().split(/\s+as\s+/)[0].trim();
      if (!name || name.startsWith("type ") || name === "LucideIcon") continue;
      names.add(name);
    }
  }
}

const kebab = (s) =>
  s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Za-z])([0-9])/g, "$1-$2").toLowerCase();

const sorted = [...names].sort();
const css = [];
const exportsTs = [];
for (const name of sorted) {
  const Icon = lucide[name];
  if (!Icon) throw new Error(`lucide-react has no icon "${name}"`);
  const svg = renderToStaticMarkup(React.createElement(Icon, { color: "black" }))
    .replace(/ class="[^"]*"/g, "")
    .replace(/ aria-hidden="true"/g, "")
    .replace(/ width="24" height="24"/, "");
  // Minimal data-URI encoding: single quotes inside, escape only what CSS
  // url() and SVG need (%, #, <, >). About half the size of
  // encodeURIComponent.
  const dataUri = svg
    .replace(/"/g, "'")
    .replace(/%/g, "%25")
    .replace(/#/g, "%23")
    .replace(/</g, "%3C")
    .replace(/>/g, "%3E")
    .replace(/\s+/g, " ");
  const cls = `ico-${kebab(name)}`;
  css.push(`.${cls}{--ico:url("data:image/svg+xml,${dataUri}")}`);
  exportsTs.push(`export const ${name} = make("${cls}", "${name}");`);
}

// Inside @layer components, and the base rule uses :where() (zero
// specificity), so any size/colour class on the element (h-4 w-4, cm-ic05,
// text-*) wins regardless of stylesheet order, exactly as on the <svg>.
const cssOut = `/* GENERATED by scripts/gen-mask-icons.cjs; do not edit. */
@layer components {
:where(.ico){display:block;width:24px;height:24px;background-color:currentColor;-webkit-mask:var(--ico) center/100% 100% no-repeat;mask:var(--ico) center/100% 100% no-repeat}
${css.join("\n")}
}
`;
fs.writeFileSync(path.join(PRODUCTS, "product-icons.css"), cssOut);

const tsOut = `/* GENERATED by scripts/gen-mask-icons.cjs; do not edit by hand. */
// Drop-in replacements for the lucide-react icons used on product pages.
// They render a <span> whose shape is a CSS mask (product-icons.css) instead
// of an inline <svg>, which Next.js would ship twice per icon (HTML + RSC).
import type { CSSProperties } from "react";
import type { LucideIcon } from "lucide-react";

export type { LucideIcon } from "lucide-react";

type MaskIconProps = {
  className?: string;
  style?: CSSProperties;
  "aria-label"?: string;
  "aria-hidden"?: boolean | "true" | "false";
};

function make(iconClass: string, name: string): LucideIcon {
  const MaskIcon = ({ className, style, "aria-label": label }: MaskIconProps) =>
    label ? (
      <span
        role="img"
        aria-label={label}
        className={className ? \`ico \${iconClass} \${className}\` : \`ico \${iconClass}\`}
        style={style}
      />
    ) : (
      <span
        aria-hidden="true"
        className={className ? \`ico \${iconClass} \${className}\` : \`ico \${iconClass}\`}
        style={style}
      />
    );
  MaskIcon.displayName = name;
  return MaskIcon as unknown as LucideIcon;
}

${exportsTs.join("\n")}
`;
fs.writeFileSync(path.join(ROOT, "components", "ui", "mask-icons.tsx"), tsOut);
console.log(`${sorted.length} icons -> product-icons.css (${Math.round(cssOut.length / 1024)} KB), mask-icons.tsx`);
